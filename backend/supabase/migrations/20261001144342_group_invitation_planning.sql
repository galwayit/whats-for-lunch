-- Invitation essentials and guest counterproposals. All mutations use authenticated
-- edge handlers and service-only RPCs; possessing a link never grants host authority.
alter table public.groups
  add column budget_per_person_minor integer check (budget_per_person_minor between 0 and 1000000),
  add column currency_code text not null default 'AUD' check (currency_code ~ '^[A-Z]{3}$'),
  add column payment_arrangement text not null default 'undecided'
    check (payment_arrangement in ('undecided', 'pay_own', 'split_equally', 'host_pays')),
  add column payment_method text not null default 'undecided'
    check (payment_method in ('undecided', 'at_venue', 'cash', 'card', 'bank_transfer'));

create table public.group_suggestions (
  id uuid primary key default gen_random_uuid(),
  group_id uuid not null references public.groups(id) on delete cascade,
  rsvp_id uuid not null references public.rsvps(id) on delete cascade,
  display_name text not null check (length(btrim(display_name)) between 1 and 60),
  place_name text check (length(btrim(place_name)) between 1 and 200),
  place_address text check (length(btrim(place_address)) between 1 and 400),
  scheduled_at timestamptz,
  note text check (length(btrim(note)) between 1 and 500),
  status text not null default 'pending' check (status in ('pending', 'accepted', 'declined', 'superseded')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  check (place_name is not null or scheduled_at is not null),
  check (place_address is null or place_name is not null)
);
create unique index group_suggestions_one_pending on public.group_suggestions(group_id, rsvp_id) where status = 'pending';
create index group_suggestions_group_created on public.group_suggestions(group_id, created_at desc);
alter table public.group_suggestions enable row level security;
revoke all on public.group_suggestions from public, anon, authenticated;
grant all on public.group_suggestions to service_role;

-- Group lock serialises duplicate submissions, review, and cancellation. New anonymous
-- identities get a random 256-bit token generated by the edge; existing tokens must match.
create function public.submit_group_suggestion(
  p_code text, p_user_id uuid, p_guest_token text, p_display_name text,
  p_place_name text, p_place_address text, p_scheduled_at timestamptz, p_note text
) returns jsonb language plpgsql security invoker set search_path = '' as $$
declare g public.groups; r public.rsvps; s public.group_suggestions;
begin
  select * into g from public.groups where invite_code = p_code and cancelled_at is null for update;
  if not found then raise exception 'Invitation not found' using errcode = 'P0002'; end if;
  if g.host_id = p_user_id then raise exception 'Hosts can edit this lunch from the group screen' using errcode = '22023'; end if;
  if g.scheduled_at <= now() then raise exception 'This lunch has already started' using errcode = '22023'; end if;
  if p_scheduled_at is not null and p_scheduled_at <= now() then
    raise exception 'Choose a future time' using errcode = '22023';
  end if;
  if p_user_id is not null then
    select * into r from public.rsvps where group_id = g.id and guest_user_id = p_user_id;
  elsif p_guest_token ~ '^[a-f0-9]{64}$' then
    select * into r from public.rsvps where group_id = g.id and guest_token = p_guest_token;
  else raise exception 'Guest identity is required' using errcode = '22023';
  end if;
  if r.id is null then
    if nullif(btrim(p_display_name), '') is null then raise exception 'Your name is required' using errcode = '22023'; end if;
    insert into public.rsvps(group_id, guest_user_id, guest_token, display_name, status)
      values (g.id, p_user_id, case when p_user_id is null then p_guest_token end, p_display_name, 'pending') returning * into r;
  end if;
  select * into s from public.group_suggestions where group_id = g.id and rsvp_id = r.id and status = 'pending';
  if found then return to_jsonb(s) || jsonb_build_object('new_submission', false); end if; -- retry-safe: keep the first pending proposal
  if (select count(*) from public.group_suggestions where group_id = g.id) >= 200
     or (select count(*) from public.group_suggestions where rsvp_id = r.id) >= 10 then
    raise exception 'Suggestion limit reached for this lunch' using errcode = '22023';
  end if;
  insert into public.group_suggestions(group_id, rsvp_id, display_name, place_name, place_address, scheduled_at, note)
    values (g.id, r.id, r.display_name, p_place_name, p_place_address, p_scheduled_at, p_note) returning * into s;
  return to_jsonb(s) || jsonb_build_object('new_submission', true);
end $$;

create function public.review_group_suggestion(p_group_id uuid, p_suggestion_id uuid, p_host_id uuid, p_accept boolean)
returns jsonb language plpgsql security invoker set search_path = '' as $$
declare g public.groups; s public.group_suggestions;
begin
  select * into g from public.groups where id = p_group_id and cancelled_at is null for update;
  if not found then raise exception 'Group not found' using errcode = 'P0002'; end if;
  if p_host_id is null or g.host_id <> p_host_id then raise exception 'Only the host can review suggestions' using errcode = '42501'; end if;
  if p_accept is null then raise exception 'A decision is required' using errcode = '22023'; end if;
  select * into s from public.group_suggestions where id = p_suggestion_id and group_id = g.id for update;
  if not found then raise exception 'Suggestion not found' using errcode = 'P0002'; end if;
  if s.status <> 'pending' then raise exception 'This suggestion has already been reviewed. Refresh the lunch.' using errcode = '22023'; end if;
  if g.scheduled_at <= now() or (p_accept and s.scheduled_at is not null and s.scheduled_at <= now()) then
    raise exception 'This time has passed. Ask for a new suggestion.' using errcode = '22023';
  end if;
  update public.group_suggestions set status = case when p_accept then 'accepted' else 'declined' end,
    reviewed_at = now() where id = s.id;
  if p_accept then
    update public.groups set scheduled_at = coalesce(s.scheduled_at, scheduled_at),
      place_name = coalesce(s.place_name, place_name),
      place_address = case when s.place_name is not null then s.place_address else place_address end,
      place_id = case when s.place_name is not null then null else place_id end
      where id = g.id returning * into g;
    -- Prior RSVPs applied to the old plan. Never silently accept on someone's behalf.
    update public.rsvps set status = 'pending', responded_at = null where group_id = g.id;
    update public.group_suggestions set status = 'superseded', reviewed_at = now()
      where group_id = g.id and status = 'pending';
  end if;
  return to_jsonb(g);
end $$;
revoke all on function public.submit_group_suggestion(text, uuid, text, text, text, text, timestamptz, text) from public, anon, authenticated;
revoke all on function public.review_group_suggestion(uuid, uuid, uuid, boolean) from public, anon, authenticated;
grant execute on function public.submit_group_suggestion(text, uuid, text, text, text, text, timestamptz, text) to service_role;
grant execute on function public.review_group_suggestion(uuid, uuid, uuid, boolean) to service_role;

-- Cost/payment changes also need a fresh RSVP. Host-name spelling changes do not.
create function public.update_group_details(p_group_id uuid, p_host_id uuid, p_host_name text,
  p_budget integer, p_currency text, p_arrangement text, p_method text)
returns jsonb language plpgsql security invoker set search_path = '' as $$
declare g public.groups; changed boolean;
begin
  select * into g from public.groups where id = p_group_id and cancelled_at is null for update;
  if not found then raise exception 'Group not found' using errcode = 'P0002'; end if;
  if p_host_id is null or g.host_id <> p_host_id then raise exception 'Only the host can edit details' using errcode = '42501'; end if;
  if nullif(btrim(p_host_name), '') is null or length(p_host_name) > 60 then raise exception 'Host name is required' using errcode = '22023'; end if;
  changed := (g.budget_per_person_minor, g.currency_code, g.payment_arrangement, g.payment_method)
    is distinct from (p_budget, p_currency, p_arrangement, p_method);
  update public.groups set host_name = p_host_name, budget_per_person_minor = p_budget, currency_code = p_currency,
    payment_arrangement = p_arrangement, payment_method = p_method where id = g.id returning * into g;
  if changed then update public.rsvps set status = 'pending', responded_at = null where group_id = g.id; end if;
  return to_jsonb(g);
end $$;
revoke all on function public.update_group_details(uuid, uuid, text, integer, text, text, text) from public, anon, authenticated;
grant execute on function public.update_group_details(uuid, uuid, text, integer, text, text, text) to service_role;
